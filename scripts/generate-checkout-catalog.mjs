import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const contentPath = path.join(root, "content", "site.json");
const outputDirectory = path.join(root, "functions", "_generated");
const outputPath = path.join(outputDirectory, "catalog.ts");

const data = JSON.parse(fs.readFileSync(contentPath, "utf8"));
const currency = String(data.commerce?.currency ?? "USD").toLowerCase();
const sessionExpiryMinutes = Number(data.commerce?.sessionExpiryMinutes ?? 30);

if (!Number.isInteger(sessionExpiryMinutes) || sessionExpiryMinutes < 30 || sessionExpiryMinutes > 1440) {
  throw new Error("commerce.sessionExpiryMinutes must be an integer from 30 through 1440.");
}

const products = Object.fromEntries(
  (data.products ?? []).map((product) => {
    const numericPrice = Number(product.price);
    const unitAmount = Math.round(numericPrice * 100);

    if (!product.slug || !product.name) {
      throw new Error("Every checkout product needs a slug and name.");
    }

    if (!Number.isFinite(numericPrice) || numericPrice <= 0 || unitAmount <= 0) {
      throw new Error(`Product ${product.slug} needs a positive price.`);
    }

    if (!Number.isInteger(product.quantity) || product.quantity < 0) {
      throw new Error(`Product ${product.slug} needs a non-negative integer quantity.`);
    }

    return [
      product.slug,
      {
        slug: product.slug,
        name: product.name,
        category: product.category,
        status: product.status,
        quantity: product.quantity,
        currency,
        unitAmount,
      },
    ];
  }),
);

const settings = {
  provider: data.commerce?.provider ?? "stripe",
  checkoutMode: data.commerce?.checkoutMode ?? "stripe-checkout-sessions",
  checkoutEnabled: Boolean(data.commerce?.checkoutEnabled),
  sessionExpiryMinutes,
  shippingCountries: data.commerce?.shippingCountries ?? ["US"],
  automaticTaxEnabled: Boolean(data.commerce?.automaticTaxEnabled),
};

const file = `// Generated by scripts/generate-checkout-catalog.mjs. Do not edit directly.\n\nexport const checkoutSettings = ${JSON.stringify(settings, null, 2)} as const;\n\nexport const checkoutCatalog = ${JSON.stringify(products, null, 2)} as const;\n\nexport type CheckoutProduct = (typeof checkoutCatalog)[keyof typeof checkoutCatalog];\n`;

fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(outputPath, file, "utf8");
console.log(`Generated ${path.relative(root, outputPath)} with ${Object.keys(products).length} products.`);
